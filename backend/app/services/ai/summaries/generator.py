"""ExecutiveSummarySuiteGenerator — Sprint H8.7 One-Click Multi-Audience Executive Summary Suite."""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class ExecutiveSummaryCard:
    """Audience-tailored executive summary card."""

    audience: str  # "ceo", "investor", "bank", "export", "risk", "growth", "compliance"
    title: str
    headline: str
    key_highlights: tuple[str, ...] = field(default_factory=tuple)
    metrics_block: dict[str, Any] = field(default_factory=dict)
    strategic_recommendation: str = ""
    disclaimer: str = "Confidential business document — generated by UrsBiz AI OS"

    def to_markdown(self) -> str:
        """Format executive summary card as a clean, professional Markdown card."""
        lines: list[str] = []
        lines.append(f"### {self.title.upper()}")
        lines.append(f"*{self.headline}*")
        lines.append("")
        if self.metrics_block:
            lines.append("**Key Audience Indicators:**")
            for k, v in self.metrics_block.items():
                lines.append(f"- **{k.replace('_', ' ').title()}**: {v}")
            lines.append("")

        if self.key_highlights:
            lines.append("**Executive Highlights:**")
            for h in self.key_highlights:
                lines.append(f"- {h}")
            lines.append("")

        if self.strategic_recommendation:
            lines.append(f"**Strategic Priority**: {self.strategic_recommendation}")
            lines.append("")

        lines.append(f"_{self.disclaimer}_")
        return "\n".join(lines)


@dataclass(frozen=True)
class ExecutiveSummarySuite:
    """Suite of 7 multi-audience executive summaries."""

    ceo_summary: ExecutiveSummaryCard
    investor_summary: ExecutiveSummaryCard
    bank_summary: ExecutiveSummaryCard
    export_summary: ExecutiveSummaryCard
    risk_summary: ExecutiveSummaryCard
    growth_summary: ExecutiveSummaryCard
    compliance_summary: ExecutiveSummaryCard

    def to_markdown(self) -> str:
        """Render complete 7-summary suite as a unified report."""
        cards = [
            self.ceo_summary,
            self.investor_summary,
            self.bank_summary,
            self.export_summary,
            self.risk_summary,
            self.growth_summary,
            self.compliance_summary,
        ]
        lines = ["# URSBIZ EXECUTIVE SUMMARY SUITE", ""]
        for card in cards:
            lines.append(card.to_markdown())
            lines.append("\n---\n")
        return "\n".join(lines)


